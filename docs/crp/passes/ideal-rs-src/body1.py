"""Research Strategy prose, part 1: Significance and Innovation."""

SIGNIFICANCE = r"""
<p class="sec first-sec"><b>The unmet need.</b> If we are fortunate, each of us will
reach the point where we, or someone we love, needs help with the ordinary tasks of
daily living: bathing, dressing, meals, medications, and moving safely through the
home. Most families meet that moment at its worst, after a fall, a diagnosis, or a
sudden hospitalization, and are expected to become experts in eldercare overnight.</p>

<p>A recognized need becomes established care only if a family clears three gates
(Figure 1). They must <b>find</b> the right care inside a fragmented ecosystem of public
aid programs, insurance coverage, healthcare services, and long-term services and
supports, each with separate eligibility rules and none accountable for whether care
begins. They must <b>afford</b> it: full-time home care runs $80,080 a year,<sup>REF2</sup>
Medicare does not cover custodial home care, and Medicaid, the nation's largest payer of
long-term care, pays only after a family has spent down to eligibility. An estimated
$58 billion in assistance that would close part of that gap goes unclaimed every year
because families cannot identify or navigate the programs.<sup>REF1</sup> And someone
must be available to <b>deliver</b> the care: 63.3 percent of home-care providers
declined cases in 2023 that they could not staff.<sup>REF3</sup></p>

<p>Failure at any one gate produces the same outcome. Needs go unmet, function declines,
a crisis arrives with an emergency visit or a hospitalization, and discharge returns the
older adult home without the support that was missing in the first place. Nearly a third
of older adults with difficulty in activities of daily living report going without
bathing, meals, or medications in a given month,<sup>REF4</sup> and unmet needs of this
kind independently predict emergency department use, readmission, nursing home
placement, and mortality.<sup>REF5,REF6,REF7</sup> Families of modest means therefore
wait, and decline care, until a hospitalization, when public programs finally step in at
the most expensive possible moment and after the most harm has already occurred.</p>

<p class="sec"><b>What it costs, and who pays it.</b> The gap is widening from both
sides. The population over 65 reaches 82 million by 2050,<sup>REF8</sup> while the
family capacity that has always absorbed most of American eldercare is contracting: the
number of potential family caregivers for each adult over 80 falls from more than seven
in 2010 to four by 2030 (Figure 2).<sup>REF9</sup> The paid workforce that would have to
replace it faces 9.7 million direct-care job openings between 2024 and
2034.<sup>REF10</sup> Demand is rising against two supplies that are falling at once.</p>

<p>The costs of that gap do not disappear. They move, and they grow in transit. Roughly
70 percent of working-age family caregivers hold jobs, and the hours they lose are borne
by employers and by their own earnings.<sup>REF11</sup> Families spend down their savings
and Medicaid inherits the bill at the institutional rate. The clearest measurement of the
inversion comes from CAPABLE, a home-based, function-focused support program whose
implementation was associated with roughly $3,000 in program cost against more than
$20,000 in reduced Medicaid spending per participant, driven by lower inpatient and
outpatient use.<sup>REF12</sup> The same approach reduced disability across multiple
randomized trials.<sup>REF13</sup></p>

<p><b>The money to support older adults at home largely exists already. It is simply
spent later, on worse outcomes, by whoever is left holding the consequence.</b> Every
dollar of that consequence sits on an identifiable balance sheet: a health plan's, a
state Medicaid budget's, a health system's, an employer's, or a family's. That is what
makes this an addressable market and not only a public health problem.</p>

<p class="sec"><b>What establishing care actually requires.</b> Closing the gap is not a
matter of better information. A family that knows exactly which program it qualifies for
still has to complete the application, gather supporting documents, file, wait, respond
to requests, and then find a provider with capacity on the date the benefit starts.
Existing help stops before that point. Clinicians and discharge planners hand off.
Information services return lists. Referral marketplaces introduce a provider and are
paid on placement. None of them is accountable for whether care was established, and none
of them can create a caregiver who does not exist.</p>

<p>Two things are therefore required at once: navigation that runs all the way to a
confirmed start, and capacity on the other side so that the start is possible. Neither is
sufficient alone, which is the central structural claim of this application.</p>

<p class="sec"><b>Why navigation alone cannot close the gap.</b> A navigation product
that clears the first two gates aggregates family demand and delivers it to a supply
side that cannot absorb it. The result is a faster path to the same refusal. This is
not a hypothetical constraint: it is the reason nearly two-thirds of home-care providers
turned away business in 2023.<sup>REF3</sup></p>

<p>Olera did not select workforce development as an adjacent business opportunity. We
encountered it as the binding constraint on our own product working. That is why
capacity creation sits inside the product rather than beside it, and why this
application proposes to test both halves in the same markets at the same time.</p>

<p class="sec"><b>The product and the path to market.</b> CareNavigator is an eldercare
AI navigation system built over an expert-curated national database of aid programs and
providers, developed across NIA SBIR Phases I through IIB. It screens a household's needs
and means, identifies the aid and services that fit, and, with the agent layer entering
production in the remaining Phase IIB year, executes the applications and follows each
case to a decision. Alongside it, Olera recruits and verifies new caregivers and places
them with licensed providers, who hire, train, insure, and supervise them as employees.</p>

<p>Families use CareNavigator at no cost, and no provider pays to be listed or to receive
a family connection. Because no fee is charged for a referral, no steering incentive
exists and federally reimbursed providers can participate, which pay-per-referral models
cannot accommodate. Revenue comes from one optional provider product during this award:
<b>Caregiver Staffing</b>.</p>

<p class="sec"><b>Market segments and customers.</b> The beachhead customer is the
healthcare and long-term services provider. Roughly 165,000 such organizations operate in
the United States,<sup>REF15,REF16</sup> and they already spend at least $5 billion a year
on marketing and caregiver recruiting, an estimate built entirely from published low-end
inputs.<sup>REF17</sup> They buy from us for an auditable reason. The published median
cost of acquiring a caregiver is $520 per hire, and that figure is for word-of-mouth, the
cheapest channel an agency has.<sup>REF18</sup> Table 1 sets our pricing against that
benchmark on the provider's own numbers.</p>

<p><b>We do not ask providers to believe in a new category. We ask them to pay less for
something they already buy.</b> Break-even against the benchmark arrives at 6.3 hires a
year, which is an agency of roughly eight caregivers, so every larger agency is ahead
from the first month. The revenue side is larger still: at 63.3 percent of agencies
declining cases they cannot staff, the opportunity cost of an unfilled role dwarfs the
subscription price.</p>

<p>A second customer class is emerging and this award evidences rather than sells to it.
Medicare now pays directly for care navigation, caregiver support, and respite through
the GUIDE model, which began in July 2024.<sup>REF19</sup> Medicare Advantage plans,
Medicaid managed care organizations, health systems and accountable care organizations,
self-insured employers, and long-term care insurers each bear part of the cost of unmet
need. Aim 3 produces the evidence package these organizations require before contracting;
it does not assume they will.</p>

<p class="sec"><b>Competitive environment and our advantage.</b> Table 2 places
CareNavigator against every category of alternative across the five stages of the path to
care. The pattern rather than any single row is the argument: <b>every alternative solves
one stretch of the path and stops at a handoff, and the handoffs are where families are
lost.</b> Human navigators are the strongest competitor and cover four of the five
stages; they are also scarce, episodic, and cannot be scaled by hiring, which is the same
workforce constraint from a different direction. Staffing channels move workers between
employers, so one provider's hire is another's vacancy and the national shortage does not
shrink. Referral marketplaces charge placement fees, which determines who appears and has
drawn sustained criticism of the incentives it creates.<sup>REF22</sup></p>

<p class="sec"><b>Related development efforts in academia and industry.</b> Most of the
relevant science is settled and what remains open is operational, which is the reason
this is a commercialization award rather than a trial. Research on unmet need, largely
from the National Health and Aging Trends Study and Medicare-linked cohorts, establishes
that unmet daily-activity needs predict downstream utilization and
placement.<sup>REF4,REF5</sup> We treat that as established and measure care established
rather than clinical endpoints. Home-based support trials, principally CAPABLE, show that
function-focused support reduces disability with savings well above program
cost;<sup>REF12,REF13</sup> what no trial addresses is how a family outside a trial finds
such support, funds it, and gets it started, and CareNavigator is the front door those
programs assume already exists. Work on digital caregiver tools, including four
peer-reviewed studies of our own, establishes that such platforms can be built and
measured as usable and accepted;<sup>REF25,REF26,REF27,REF28</sup> what remains open is
whether AI agents can complete applications and carry a case to a decision. Payer-funded
navigation is no longer speculative, given the GUIDE model.<sup>REF19</sup> And research
on health-professions admissions establishes that documented patient-care hours are a
requirement for entry,<sup>REF23,REF24</sup> which is the incentive our workforce pathway
uses; whether that requirement converts into durable eldercare capacity is what Aim 2
tests.</p>

<p class="sec"><b>Hurdles to adoption.</b> The primary hurdle is local density at a cost
the market sustains: families, providers, and caregivers must concentrate in the same
market, and that market's revenue must cover the cost of bringing them together. Four
specific hurdles follow. Families must trust an AI system with care decisions, which we
address by drawing every answer from an expert-curated database audited by domain
experts and by validating acceptance under IRB approval in Aim 1. Providers are wary of
platforms, so they begin at no cost and are asked to pay only after value has been
delivered, with conversion and churn measured under real billing in Aim 3. New caregivers
must be safe and welcome, which is why licensed providers employ, train, insure, and
supervise them, and why Aim 2 measures the pathway end to end. And every market must
repeat affordably, which self-service portals and a documented market-entry playbook
address, with acquisition cost per market measured in Aims 1 and 2.</p>
"""

INNOVATION = r"""
<p class="sec first-sec"><b>Key Innovation 1: capacity created, not moved.</b> Every
staffing channel serving this industry, whether an agency, a job board, or a gig
platform, competes for workers already inside the direct-care labor market. One
provider's hire is another provider's vacancy, and the national shortage does not shrink
by a single worker. Olera adds people who were not in the field (Figure 3).</p>

<p>The first population tested is health-professions students, chosen because admission
to their programs requires documented patient-care hours, which makes recruitment
structurally inexpensive rather than dependent on wage competition. Health professions
confer 263,800 undergraduate degrees a year,<sup>REF23</sup> and entry into nursing,
medicine, and physician assistant training turns on documented direct patient
care.<sup>REF24</sup> Our own pilot drew more than 900 applicants. New cohorts arrive
every semester, so the pipeline refills rather than depleting.</p>

<p><b>The innovation is not the student channel, which any competitor could copy.</b> It
is the infrastructure underneath it: the machinery that converts a person who has never
worked in eldercare into someone a licensed provider will hire, and that carries their
verified record of hours, competencies, populations served, supervisor evaluations, and
credential status forward across employers. That layer is what makes any new worker pool
viable, and its value compounds with every shift worked. Task 2.5 tests a second,
non-student pool against the same pathway in two campus-poor markets, converting
extensibility from an assertion into a demonstrated result.</p>

<p class="sec"><b>Key Innovation 2: execution, not information.</b> The prevailing
paradigm is that tools inform and families execute. A family is told which programs it
may qualify for and is then left to prepare applications, gather documents, file, wait,
respond to requests, and confirm that care began. Those are precisely the steps at which
families are lost, and no existing tool is accountable for them.</p>

<p>CareNavigator's agents perform the work and the family decides. <b>The unit of success
changes from information delivered to care established.</b> That shift is what makes the
outcome measurable, what makes it saleable to an organization that bears the cost of
unmet need, and what makes the system improve: every completed case becomes supervised
training data for the next one. The technical foundation, a multi-agent architecture over
a retrieval layer with expert feedback, was built and evaluated under Phase IIB; what
this award adds is execution and confirmation.</p>

<p class="sec"><b>Key Innovation 3: a county-level record of what actually happens.</b>
Eldercare information exists in three layers. The open web holds public directories and
program rules, often neither accurate nor current, and it is equally available to any
general-purpose AI system. Beneath that sit local program realities and provider truths
that were never published, which we assembled through field work, expert curation, and
direct outreach into more than 72,000 records covering all fifty states. Beneath that
sits a third layer that can only be learned by operating: what programs actually decide,
county by county, where applications stall, whether capacity existed when it was needed,
and what care ultimately started.</p>

<p>No public dataset holds the third layer. NHATS is a survey. Claims data record what
was billed, not what was needed and refused. <b>What this project builds is the first
longitudinal, county-level administrative record of what older adults need, what they
qualify for, where the system fails them, and whether care was established.</b> Its
commercial value is that a competitor who copies every feature begins with an empty
database. Its scientific value is that this measurement does not currently exist for
researchers or for the state agencies that plan around it, and we commit to publishing
from it.</p>
"""
